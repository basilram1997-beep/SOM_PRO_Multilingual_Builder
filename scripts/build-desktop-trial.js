const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const { error, log } = require("./cli-output");

const npmCommand = process.platform === "win32" ? "npm.cmd" : "npm";
const runtimeConfigPath = path.resolve(__dirname, "..", "apps", "desktop", "som-pro-runtime.env");
const runtimeConfigBackupPath = `${runtimeConfigPath}.build-backup`;
function commandForPlatform(command, args) {
  if (process.platform === "win32" && /\.cmd$/i.test(command)) {
    return {
      command: process.env.ComSpec || "cmd.exe",
      args: ["/d", "/c", command, ...args]
    };
  }
  return { command, args };
}
const env = {
  ...process.env,
  SOM_RUNTIME_MODE: process.env.SOM_RUNTIME_MODE || "local-trial"
};

function writeRuntimeConfig() {
  const content = [
    "# Generated by npm run release:build:trial",
    "SOM_RUNTIME_MODE=local-trial",
    "SOM_API_URL=http://localhost:4000",
    "VITE_API_URL=http://localhost:4000",
    "SOM_LICENSE_SERVER_URL=http://localhost:4100",
    "SOM_PRO_LICENSE_SERVER_URL=http://localhost:4100",
    ""
  ].join("\n");
  fs.writeFileSync(runtimeConfigPath, content, "utf8");
  log("Runtime config written:", runtimeConfigPath);
}

function backupRuntimeConfig() {
  if (fs.existsSync(runtimeConfigPath)) {
    fs.copyFileSync(runtimeConfigPath, runtimeConfigBackupPath);
  }
}

function restoreRuntimeConfig() {
  if (fs.existsSync(runtimeConfigBackupPath)) {
    fs.copyFileSync(runtimeConfigBackupPath, runtimeConfigPath);
    fs.unlinkSync(runtimeConfigBackupPath);
    return;
  }
  if (fs.existsSync(runtimeConfigPath)) {
    fs.unlinkSync(runtimeConfigPath);
  }
}

function run(command, args, options = {}) {
  const prepared = commandForPlatform(command, args);
  const result = spawnSync(prepared.command, prepared.args, { stdio: "inherit", env, shell: false, ...options });
  if (result.error) {
    error(result.error.message);
    process.exit(1);
  }
  if (result.status !== 0) process.exit(result.status || 1);
}

log("Building Desktop Trial package");
backupRuntimeConfig();
try {
  writeRuntimeConfig();
  run(npmCommand, ["run", "build:frontend"]);
  run(npmCommand, ["run", "desktop:check"]);
  run(npmCommand, ["run", "desktop:build:win"]);
  run(process.execPath, ["scripts/rename-desktop-installer.js", "Trial"], { shell: false });
} finally {
  restoreRuntimeConfig();
}
