const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const { success, warn } = require("../cli-output");

const root = path.resolve(__dirname, "..", "..");
const domain = process.env.SOM_STAGING_DOMAIN || "sompro.duckdns.org";
const appUrl = `https://${domain}`;
const apiUrl = `${appUrl}/api`;
const licenseUrl = `${appUrl}/license`;

function randomSecret(bytes = 32) {
  return crypto.randomBytes(bytes).toString("base64url");
}

function writeEnv(file, values) {
  const fullPath = path.join(root, file);
  if (fs.existsSync(fullPath) && !process.argv.includes("--force")) {
    warn("kept existing:", file);
    return;
  }

  fs.mkdirSync(path.dirname(fullPath), { recursive: true });
  const content = [
    "# Generated by npm run staging:prepare-duckdns",
    "# Local staging deployment file. Do not commit real secrets.",
    ...values.map(([key, value]) => `${key}=${value}`),
    ""
  ].join("\n");
  fs.writeFileSync(fullPath, content, { encoding: "utf8", mode: 0o600 });
  success("wrote:", file);
}

