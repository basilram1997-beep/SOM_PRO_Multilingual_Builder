const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const { error, log } = require("./cli-output");

const apiUrl = process.env.SOM_API_URL || process.env.VITE_API_URL || "";
const licenseUrl = process.env.SOM_LICENSE_SERVER_URL || process.env.SOM_PRO_LICENSE_SERVER_URL || "";
const apiEnv = process.env.SOM_API_ENV || "staging";
const npmCommand = process.platform === "win32" ? "npm.cmd" : "npm";
const runtimeConfigPath = path.resolve(__dirname, "..", "apps", "desktop", "som-pro-runtime.env");
const runtimeConfigBackupPath = `${runtimeConfigPath}.build-backup`;
function assertProductionUrl(name, value) {
  const raw = String(value || "").trim();
  if (!raw) {
    error(`${name} is required for a SaaS build.`);
    process.exit(1);
  }
  let parsed;
  try {
    parsed = new URL(raw);
  } catch {
    error(`${name} must be a valid URL. Received: ${raw}`);
    process.exit(1);
  }
  const forbidden = ["localhost", "127.0.0.1", "::1"];
  const host = parsed.hostname.toLowerCase();
  if (
    parsed.protocol !== "https:" ||
    forbidden.includes(host) ||
    host.endsWith(".example") ||
    host.includes("example.com") ||
    host.includes("sompro.example")
  ) {
    error(`${name} must be a real HTTPS production/staging URL, not localhost or a placeholder. Received: ${raw}`);
    process.exit(1);
  }
}

function validateSaasBuildEnvironment() {
  assertProductionUrl("SOM_API_URL/VITE_API_URL", apiUrl);
  assertProductionUrl("SOM_LICENSE_SERVER_URL", licenseUrl);
}
function commandForPlatform(command, args) {
  if (process.platform === "win32" && /\.cmd$/i.test(command)) {
    return {
      command: process.env.ComSpec || "cmd.exe",
      args: ["/d", "/c", command, ...args]
    };
  }
  return { command, args };
}
const env = {
  ...process.env,
  SOM_RUNTIME_MODE: "saas",
  SOM_API_ENV: apiEnv,
  SOM_API_URL: apiUrl,
  VITE_API_URL: apiUrl,
  SOM_LICENSE_SERVER_URL: licenseUrl,
  SOM_PRO_LICENSE_SERVER_URL: licenseUrl
};

function writeRuntimeConfig() {
  const content = [
    "# Generated by npm run release:build:saas",
    "# This file is bundled with the desktop app and contains no server secrets.",
    "SOM_RUNTIME_MODE=saas",
    `SOM_API_ENV=${apiEnv}`,
    `SOM_API_URL=${apiUrl}`,
    `VITE_API_URL=${apiUrl}`,
    `SOM_LICENSE_SERVER_URL=${licenseUrl}`,
    `SOM_PRO_LICENSE_SERVER_URL=${licenseUrl}`,
    ""
  ].join("\n");
  fs.writeFileSync(runtimeConfigPath, content, "utf8");
  log("Runtime config written:", runtimeConfigPath);
}

function backupRuntimeConfig() {
  if (fs.existsSync(runtimeConfigPath)) {
    fs.copyFileSync(runtimeConfigPath, runtimeConfigBackupPath);
  }
}

function restoreRuntimeConfig() {
  if (fs.existsSync(runtimeConfigBackupPath)) {
    fs.copyFileSync(runtimeConfigBackupPath, runtimeConfigPath);
    fs.unlinkSync(runtimeConfigBackupPath);
    return;
  }
  if (fs.existsSync(runtimeConfigPath)) {
    fs.unlinkSync(runtimeConfigPath);
  }
}

function run(command, args, options = {}) {
  const prepared = commandForPlatform(command, args);
  const result = spawnSync(prepared.command, prepared.args, { stdio: "inherit", env, shell: false, ...options });
  if (result.error) {
    error(result.error.message);
    process.exit(1);
  }
  if (result.status !== 0) process.exit(result.status || 1);
}

validateSaasBuildEnvironment();
log("Building Desktop SaaS package");
log("API URL:", apiUrl);
log("License Server URL:", licenseUrl);
backupRuntimeConfig();
try {
  writeRuntimeConfig();
  run(npmCommand, ["run", "build:frontend"]);
  run(npmCommand, ["run", "desktop:check:saas"]);
  run(npmCommand, ["run", "desktop:build:win"]);
  run(process.execPath, ["scripts/rename-desktop-installer.js", "SaaS"], { shell: false });
} finally {
  restoreRuntimeConfig();
}
