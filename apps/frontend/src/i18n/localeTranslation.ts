function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function applyReplacements(text: string, replacements: Replacement[]) {
  let next = text;
  for (const [from, to] of replacements) {
    const startsWithWord = /^\p{L}|\d/u.test(from);
    const endsWithWord = /\p{L}|\d$/u.test(from);
    const prefix = startsWithWord ? "(?<![\\p{L}\\p{N}_])" : "";
    const suffix = endsWithWord ? "(?![\\p{L}\\p{N}_])" : "";
    next = next.replace(new RegExp(`${prefix}${escapeRegExp(from)}${suffix}`, "giu"), to);
  }
  return next;
}

function preservePlaceholders(value: string) {
  const placeholders: string[] = [];
  let next = value.replace(/\{[^}]+\}/g, (match) => {
    placeholders.push(match);
    return `__PH_${placeholders.length - 1}__`;
  });
  next = next.replace(/\s+/g, " ").trim();
  return {
    text: next,
    restore(output: string) {
      return output.replace(/__PH_(\d+)__/g, (_, index: string) => placeholders[Number(index)] || "");
    }
  };
}

function translateEnglishText(value: string, language: SupportedLocale) {
  const trimmed = (value || "").trim();
  if (!trimmed) return trimmed;
  if (trimmed === "SOM PRO") return trimmed;

  const exactTranslation = cleanLocalizedText(exactTranslations[language][trimmed] || "");
  if (exactTranslation) return exactTranslation;

  const { text, restore } = preservePlaceholders(trimmed);
  const phraseMap = [...phraseReplacements[language]]
    .map(([from, to]) => [cleanLocalizedText(from), cleanLocalizedText(to)] as Replacement)
    .sort((left, right) => right[0].length - left[0].length);
  const tokenMap = tokenReplacements[language].map(
    ([from, to]) => [cleanLocalizedText(from), cleanLocalizedText(to)] as Replacement
  );

  let output = text;
  output = applyReplacements(output, phraseMap);
  output = applyReplacements(output, tokenMap);
  output = output
    .replace(/\s+/g, " ")
    .replace(/\s([,.;:!?])/g, "$1")
    .trim();
  return cleanLocalizedText(restore(output));
}

export function buildReviewedLocaleDictionary(english: TranslationDictionary, language: SupportedLocale) {
  const next: TranslationDictionary = {};
  for (const [key, value] of Object.entries(english)) {
    next[key] = translateEnglishText(value, language);
  }
  return next;
}
